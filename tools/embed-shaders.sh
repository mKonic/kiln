#!/usr/bin/env bash
# embed-shaders.sh OUT_HEADER SHADER... : compiles GLSL with glslc and writes SPIR-V arrays.
# quad.vert -> kQuadVert. Run by CMake at build time (cmake/Shaders.cmake).
set -euo pipefail
out="$1"; shift
GLSLC="${GLSLC:-glslc}"
tmpdir="$(mktemp -d)"; trap 'rm -rf "$tmpdir"' EXIT
{
    echo "#pragma once"
    echo "// GENERATED by tools/embed-shaders.sh from render/shaders -- do not edit."
    echo "#include <cstdint>"
    echo "namespace kiln::shaders {"
    for shader in "$@"; do
        base="$(basename "$shader")"
        name="k$(echo "${base%.*}" | sed -E 's/(^|_)([a-z])/\U\2/g')$(echo "${base##*.}" | sed -E 's/^(.)/\U\1/')"
        "$GLSLC" -O --target-env=vulkan1.1 "$shader" -o "$tmpdir/s.spv"
        echo "inline constexpr std::uint32_t ${name}[] = {"
        od -An -tx4 -v "$tmpdir/s.spv" | awk '{for(i=1;i<=NF;i++) printf "0x%s,", $i; print ""}'
        echo "};"
    done
    echo "}"
} > "$out.tmp"
mv "$out.tmp" "$out"
