TEST(ClRatio_testWrapRatio) {
    using namespace kiln::constraintlayout::core;
    Widgets W;
        auto* root = W.make<ConstraintWidgetContainer>(0, 0, 700, 1920);
        auto* a = W.make<ConstraintWidget>(231, 126);
        auto* b = W.make<ConstraintWidget>(231, 126);
        auto* c = W.make<ConstraintWidget>(231, 126);
        root->setDebugName("root");
        root->add(a);
        root->add(b);
        root->add(c);
        a->setDebugName("A");
        b->setDebugName("B");
        c->setDebugName("C");
        a->setHorizontalDimensionBehaviour(ConstraintWidget::DimensionBehaviour::MATCH_CONSTRAINT);
        a->setVerticalDimensionBehaviour(ConstraintWidget::DimensionBehaviour::MATCH_CONSTRAINT);
        a->setDimensionRatio("1:1");
        a->connect(ConstraintAnchor::Type::LEFT, root, ConstraintAnchor::Type::LEFT);
        a->connect(ConstraintAnchor::Type::RIGHT, root, ConstraintAnchor::Type::RIGHT);
        a->connect(ConstraintAnchor::Type::TOP, root, ConstraintAnchor::Type::TOP);
        a->connect(ConstraintAnchor::Type::BOTTOM, b, ConstraintAnchor::Type::TOP);
        a->setHorizontalChainStyle(ConstraintWidget::CHAIN_PACKED);
        a->setHorizontalBiasPercent(0.3f);
        a->setVerticalChainStyle(ConstraintWidget::CHAIN_SPREAD_INSIDE);
        b->connect(ConstraintAnchor::Type::LEFT, a, ConstraintAnchor::Type::LEFT, 171);
        b->connect(ConstraintAnchor::Type::TOP, a, ConstraintAnchor::Type::BOTTOM);
        b->connect(ConstraintAnchor::Type::BOTTOM, c, ConstraintAnchor::Type::TOP);
        c->connect(ConstraintAnchor::Type::LEFT, b, ConstraintAnchor::Type::LEFT);
        c->connect(ConstraintAnchor::Type::RIGHT, b, ConstraintAnchor::Type::RIGHT);
        c->connect(ConstraintAnchor::Type::TOP, b, ConstraintAnchor::Type::BOTTOM);
        c->connect(ConstraintAnchor::Type::BOTTOM, root, ConstraintAnchor::Type::BOTTOM);
        root->setVerticalDimensionBehaviour(ConstraintWidget::DimensionBehaviour::WRAP_CONTENT);
        root->setHorizontalDimensionBehaviour(ConstraintWidget::DimensionBehaviour::WRAP_CONTENT);
        root->layout();
        CHECK_EQ(a->getLeft() >= 0, true);
        CHECK_EQ(a->getWidth(), a->getHeight());
        CHECK_EQ(a->getWidth(), 402);
        CHECK_EQ(root->getWidth(), 402);
        CHECK_EQ(root->getHeight(), 654);
        CHECK_EQ(a->getLeft(), 0);
        CHECK_EQ(b->getTop(), 402);
        CHECK_EQ(b->getLeft(), 171);
        CHECK_EQ(c->getTop(), 528);
        CHECK_EQ(c->getLeft(), 171);
}

