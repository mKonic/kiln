TEST(ClAdvancedChain_testComplexChainWeights) {
    using namespace kiln::constraintlayout::core;
    Widgets W;
        auto* root = W.make<ConstraintWidgetContainer>(0, 0, 800, 800);
        auto* a = W.make<ConstraintWidget>(100, 20);
        auto* b = W.make<ConstraintWidget>(100, 20);
        root->setDebugSolverName(root->getSystem(), "root");
        a->setDebugSolverName(root->getSystem(), "A");
        b->setDebugSolverName(root->getSystem(), "B");
        a->connect(ConstraintAnchor::Type::LEFT, root, ConstraintAnchor::Type::LEFT);
        a->connect(ConstraintAnchor::Type::RIGHT, root, ConstraintAnchor::Type::RIGHT);
        b->connect(ConstraintAnchor::Type::LEFT, root, ConstraintAnchor::Type::LEFT);
        b->connect(ConstraintAnchor::Type::RIGHT, root, ConstraintAnchor::Type::RIGHT);
        a->connect(ConstraintAnchor::Type::TOP, root, ConstraintAnchor::Type::TOP, 0);
        a->connect(ConstraintAnchor::Type::BOTTOM, b, ConstraintAnchor::Type::TOP, 0);
        b->connect(ConstraintAnchor::Type::TOP, a, ConstraintAnchor::Type::BOTTOM, 0);
        b->connect(ConstraintAnchor::Type::BOTTOM, root, ConstraintAnchor::Type::BOTTOM, 0);
        root->add(a);
        root->add(b);
        a->setHorizontalDimensionBehaviour(ConstraintWidget::DimensionBehaviour::MATCH_CONSTRAINT);
        a->setVerticalDimensionBehaviour(ConstraintWidget::DimensionBehaviour::MATCH_CONSTRAINT);
        b->setHorizontalDimensionBehaviour(ConstraintWidget::DimensionBehaviour::MATCH_CONSTRAINT);
        b->setVerticalDimensionBehaviour(ConstraintWidget::DimensionBehaviour::MATCH_CONSTRAINT);
        root->setOptimizationLevel(Optimizer::OPTIMIZATION_NONE);
        root->layout();
        CHECK_EQ(a->getWidth(), 800);
        CHECK_EQ(b->getWidth(), 800);
        CHECK_EQ(a->getHeight(), 400);
        CHECK_EQ(b->getHeight(), 400);
        CHECK_EQ(a->getTop(), 0);
        CHECK_EQ(b->getTop(), 400);
        a->setDimensionRatio("16:3");
        root->layout();
        CHECK_EQ(a->getWidth(), 800);
        CHECK_EQ(b->getWidth(), 800);
        CHECK_EQ(a->getHeight(), 150);
        CHECK_EQ(b->getHeight(), 150);
        CHECK_EQ(a->getTop(), 167);
        CHECK_EQ(b->getTop(), 483);
        b->setVerticalWeight(1);
        root->layout();
        CHECK_EQ(a->getWidth(), 800);
        CHECK_EQ(b->getWidth(), 800);
        CHECK_EQ(a->getHeight(), 150);
        CHECK_EQ(b->getHeight(), 650);
        CHECK_EQ(a->getTop(), 0);
        CHECK_EQ(b->getTop(), 150);
        a->setVerticalWeight(1);
        root->layout();
        CHECK_EQ(a->getWidth(), 800);
        CHECK_EQ(b->getWidth(), 800);
        CHECK_EQ(a->getHeight(), 150);
        CHECK_EQ(b->getHeight(), 150);
        CHECK_EQ(a->getTop(), 167);
        CHECK_EQ(b->getTop(), 483);
}

