TEST(ClWrap_testBarrierWrap) {
    using namespace kiln::constraintlayout::core;
    Widgets W;
        auto* root = W.make<ConstraintWidgetContainer>(0, 0, 1080, 1080);
        auto* view = W.make<ConstraintWidget>(200, 200);
        auto* space = W.make<ConstraintWidget>(50, 50);
        auto* button = W.make<ConstraintWidget>(100, 80);
        auto* text = W.make<ConstraintWidget>(90, 30);
        auto* barrier = W.make<Barrier>();
        barrier->setBarrierType(Barrier::BOTTOM);
        barrier->add(button);
        barrier->add(space);
        root->setDebugName("root");
        view->setDebugName("view");
        space->setDebugName("space");
        button->setDebugName("button");
        text->setDebugName("text");
        barrier->setDebugName("barrier");
        root->add(view);
        root->add(space);
        root->add(button);
        root->add(text);
        root->add(barrier);
        view->connect(ConstraintAnchor::Type::TOP, root, ConstraintAnchor::Type::TOP);
        space->connect(ConstraintAnchor::Type::TOP, view, ConstraintAnchor::Type::BOTTOM);
        button->connect(ConstraintAnchor::Type::TOP, view, ConstraintAnchor::Type::BOTTOM);
        button->connect(ConstraintAnchor::Type::BOTTOM, text, ConstraintAnchor::Type::TOP);
        text->connect(ConstraintAnchor::Type::TOP, barrier, ConstraintAnchor::Type::BOTTOM);
        text->connect(ConstraintAnchor::Type::BOTTOM, root, ConstraintAnchor::Type::BOTTOM);
        button->setVerticalBiasPercent(1.0f);
        root->setVerticalDimensionBehaviour(ConstraintWidget::DimensionBehaviour::WRAP_CONTENT);
        root->layout();
        CHECK_EQ(view->getTop(), 0);
        CHECK_EQ(view->getBottom(), 200);
        CHECK_EQ(space->getTop(), 200);
        CHECK_EQ(space->getBottom(), 250);
        CHECK_EQ(button->getTop(), 200);
        CHECK_EQ(button->getBottom(), 280);
        CHECK_EQ(barrier->getTop(), 280);
        CHECK_EQ(text->getTop(), barrier->getTop());
}

